/** 按屏幕摆正的字：用宋体点阵拼起来；有宋体里没有的字就退回方块字放大两倍 */
function screenTextRows(text, font, gap) {
  const F = font || SONG
  const chars = Array.from(String(text || '').trim().toUpperCase()).filter((ch) => FONT[ch])
  if (!chars.length) return null
  if (chars.some((ch) => !F[ch])) return null
  const H = F[chars[0]].length
  const rows = []
  for (let y = 0; y < H; y += 1) rows.push(chars.map((ch) => F[ch][y]).join('0'.repeat(gap == null ? SONG_GAP : gap)))
  return rows
}

/** 位图放大两倍（每个点变成 2×2），给按屏幕摆正的几块用 */
function upscale2(rows) {
  const out = []
  rows.forEach((line) => {
    const wide = Array.from(line).map((ch) => ch + ch).join('')
    out.push(wide, wide)
  })
  return out
}

/** 把位图转置：右下那组字要沿 r 方向排，才能贴着菱形的右下边 */
function transpose(rows) {
  const h = rows.length
  const w = rows[0].length
  const out = []
  for (let x = 0; x < w; x += 1) {
    let line = ''
    for (let y = 0; y < h; y += 1) line += rows[y][x]
    out.push(line)
  }
  return out
}

