/** 「满屏截图」模式下这格在不在截图里；整块黑土模式（screen 为 false）全都算 */
function inView(r, c, size, screen) {
  if (!screen) return true
  const u = c - r
  const v = r + c - (size - 1)
  return v >= VIEW.top && v <= VIEW.bottom && Math.abs(u) <= VIEW.side
}
