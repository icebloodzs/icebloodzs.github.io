/**
 * 整块图案。按**屏幕坐标**画（菱形视角下正立），摆在上 / 下两个方向。
 *
 * 菱形格子只有 ±45° 方向的边是齐的：水平或竖直的边上，格子只能一个挨一个地错开，
 * 边缘一定是锯齿（看着就像缺了角、不圆润）。所以这几个图案的轮廓全部走 45°，
 * 也就是只沿 `p = v + u`、`q = v − u`（正好是游戏网格的两个方向）切，拼出来才是干净的一整块。
 *
 * mask(uMax, vMin, vMax, inside)：u 是屏幕横向、v 是屏幕纵向，inside 给出图形范围。
 */
function mask(uMax, vMin, vMax, inside) {
  const rows = []
  for (let v = vMin; v <= vMax; v += 1) {
    let line = ''
    for (let u = -uMax; u <= uMax; u += 1) line += inside(u, v) ? '1' : '0'
    rows.push(line)
  }
  return rows
}

/**
 * 爱心：两个菱形耳朵搭在 45° 的 V 形下半上。a = 心口深浅（耳朵中心离中线多远），R = 耳朵大小，
 * 整体半宽 a + R、心口深 a。再大一圈（a6 R6 起）上方那片就放不下了，上下两颗心会不一样大。
 */
function heartShape(a, R) {
  const w = a + R
  return (u, v) => Math.abs(Math.abs(u) - a) + Math.abs(v) <= R || (v >= 0 && Math.abs(u) <= w - v)
}

/** 十字：两条互相垂直的 45° 长条。T = 粗细，L = 长度 */
function crossShape(T, L) {
  return (u, v) => {
    const p = v + u
    const q = v - u
    return (Math.abs(q) <= T && Math.abs(p) <= L) || (Math.abs(p) <= T && Math.abs(q) <= L)
  }
}

/** 箭头：朝上的两道 45° 臂（尖朝上）。T = 粗细，L = 臂长 */
function arrowShape(T, L) {
  return (u, v) => {
    const p = v + u
    const q = v - u
    return (q >= 0 && q <= T && p >= 0 && p <= L) || (p >= 0 && p <= T && q >= 0 && q <= L)
  }
}

/**
 * 下面这几款是给「7 级城池缩小截图」上方那片空地设计的（2026-11）。
 * 菱形格子只有 45° 的边是齐的，所以都学爱心的结构：底下是一个 ∨，上面立几个 45° 的尖，
 * 尖和尖之间自然有凹口；只走 45°，拼出来没有锯齿。
 *
 * lobes(K, L, peaks)：∨ 的底尖在 v = K，半宽不超过 L；peaks = [[位置 u, 尖顶 v], …]
 */
function lobesShape(K, L, peaks) {
  return (u, v) => Math.abs(u) <= L && v <= K - Math.abs(u) && peaks.some(([c, a]) => v >= a + Math.abs(u - c))
}

/** 波浪：一条 45° 折线带子，上下起伏 —— 山河的「河」。A = 起伏高度，T = 带子粗细 */
function waveShape(A, T) {
  return (u, v) => {
    const m = ((u % (2 * A)) + 2 * A) % (2 * A)
    const y = m <= A ? m : 2 * A - m
    return v >= y && v <= y + T
  }
}

/** 宝石：一圈菱形框套一个实心小菱形 */
function gemShape(R, T, C) {
  return (u, v) => {
    const d = Math.abs(u) + Math.abs(v)
    return (d <= R && d > R - T) || d <= C
  }
}

/** 雁阵：几层往上尖的 ∧ 叠起来（︽），像雁阵 / 军衔。n 层、每层厚 T、层间空 G、半宽 L */
function chevronShape(n, T, G, L) {
  return (u, v) => {
    if (Math.abs(u) > L) return false
    const d = v - Math.abs(u)
    for (let k = 0; k < n; k += 1) {
      const top = k * (T + G)
      if (d >= top && d < top + T) return true
    }
    return false
  }
}

